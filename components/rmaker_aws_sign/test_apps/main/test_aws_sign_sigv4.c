#define AK   "AKIDEXAMPLE"
#define SK   "wJalrXUtnFEMI/K7MDENG+bPxRfiCYEXAMPLEKEY"
#define NOW  1440938160                 /* 20150830T123600Z */
#define HOST "example.amazonaws.com"

#define EMPTY_PAYLOAD_HASH "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
#define HELLO_PAYLOAD_HASH "2cf24dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824"

static esp_rmaker_aws_sign_sigv4_input_t base_input(void)
{
    esp_rmaker_aws_sign_sigv4_input_t in = {
        .method = "GET",
        .host = HOST,
        .path = "/",
        .access_key_id = AK,
        .secret_access_key = SK,
        .region = "us-east-1",
        .service = "service",
        .now_epoch_sec = NOW,
    };
    return in;
}

static void assert_signature(const esp_rmaker_aws_sign_sigv4_input_t *in, const char *expect)
{
    esp_rmaker_aws_sign_sigv4_output_t out = {0};
    TEST_ASSERT_EQUAL(ESP_OK, esp_rmaker_aws_sign_sigv4(in, &out));
    const char *sig = strstr(out.authorization_header, "Signature=");
    TEST_ASSERT_NOT_NULL(sig);
    TEST_ASSERT_EQUAL_STRING(expect, sig + strlen("Signature="));
    esp_rmaker_aws_sign_sigv4_output_free(&out);
}

